package mx.com.liverpool.p360.services.core.xml;

public class ProductFileClassificationElement {
	
	private String id = null;
	private String type = null;

	public ProductFileClassificationElement(String id, String type) {
		this.id = id;
		this.type = type;
	}

	public String getId() {
		return id;
	}

	public String getType() {
		return type;
	}
	


}
